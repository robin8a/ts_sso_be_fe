/**
 * App-client attribute permissions for the TerraSacha SSO user pool.
 *
 * Every app client (the default/sandbox client created by `defineAuth`, and the
 * per-application clients added in Task 6) must apply the same rule for the
 * custom role attribute, per Requirement 4.1 and the attribute rules in
 * 04_Data_Models.md:
 *
 *   | Rule            | Value |
 *   | --------------- | ----- |
 *   | User-writable   | no    |
 *   | Client-readable | yes   |
 *   | Admin-writable  | yes (role-assignment operation only, via the pool) |
 *
 * `custom:tsRoles` is `mutable: true` at the pool level so the admin assignment
 * API (Task 7) can set it with `AdminUpdateUserAttributes`. Pool-level
 * mutability alone does NOT stop a signed-in end user from self-writing the
 * attribute - that is controlled per app client by its *write* attributes. Keeping
 * `custom:tsRoles` out of every client's write attributes is what makes an
 * end-user attribute update of the role attribute fail (06_Testing_Strategy.md
 * negative test `ROLE_NOT_WRITABLE`), while keeping it in the read attributes
 * lets the frontend read the role for the per-app authorize chain.
 *
 * These helpers return raw Cognito attribute-name strings, the form the L1
 * `CfnUserPoolClient.readAttributes` / `writeAttributes` expect.
 */

/** Raw Cognito attribute name for the custom role parameter. */
export const TS_ROLES_ATTRIBUTE = 'custom:tsRoles';

/**
 * Standard OIDC attributes the frontend needs for the signed-in user, besides
 * the role attribute. `email` backs email login (Requirement 6.1); `profile`
 * and `email_verified` are the usual readable identity attributes.
 */
const BASE_READ_ATTRIBUTES = ['email', 'email_verified', 'profile'] as const;

/**
 * Attributes a client may let an end user write to. Deliberately EXCLUDES
 * `custom:tsRoles`: only the central admin operation writes roles, through the
 * pool, never the end user through a client. `email` stays writable so standard
 * account self-service (e.g. changing email) is unaffected.
 */
const BASE_WRITE_ATTRIBUTES = ['email', 'profile'] as const;

/**
 * Read attributes for a client: the base identity attributes plus the role
 * attribute. Client-readable: yes. Returns a fresh array each call so callers
 * can assign it to a mutable CDK property without sharing state.
 */
export function clientReadAttributes(): string[] {
  return [...BASE_READ_ATTRIBUTES, TS_ROLES_ATTRIBUTE];
}

/**
 * Write attributes for a client: the base identity attributes only. The role
 * attribute is intentionally absent so an end user cannot self-write it
 * (`ROLE_NOT_WRITABLE`). Returns a fresh array each call.
 */
export function clientWriteAttributes(): string[] {
  return [...BASE_WRITE_ATTRIBUTES];
}

/** Read attributes for the default/sandbox client generated by `defineAuth`. */
export function defaultClientReadAttributes(): string[] {
  return clientReadAttributes();
}

/** Write attributes for the default/sandbox client generated by `defineAuth`. */
export function defaultClientWriteAttributes(): string[] {
  return clientWriteAttributes();
}
